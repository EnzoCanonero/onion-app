import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lockPath = path.join(repoRoot, "package-lock.json");
const outputPath = path.join(repoRoot, "THIRD_PARTY_NOTICES.txt");

function normalizeLicense(value) {
  if (!value) return "UNKNOWN";
  if (typeof value === "string") return value.trim();
  if (Array.isArray(value)) {
    const parts = value.map(normalizeLicense).filter(Boolean);
    return parts.length > 0 ? parts.join(" OR ") : "UNKNOWN";
  }

  if (typeof value === "object") {
    if (typeof value.type === "string") return value.type.trim();
    return "UNKNOWN";
  }

  return String(value).trim() || "UNKNOWN";
}

function repoToUrl(repository) {
  if (!repository) return null;
  if (typeof repository === "string") return repository;
  if (typeof repository === "object" && typeof repository.url === "string") return repository.url;
  return null;
}

function isTextFileCandidate(filename) {
  // Many packages include LICENSE without an extension.
  if (!filename) return false;
  const base = filename.toLowerCase();
  return (
    base === "license" ||
    base === "licence" ||
    base === "copying" ||
    base === "notice" ||
    base.startsWith("license.") ||
    base.startsWith("licence.") ||
    base.startsWith("copying.") ||
    base.startsWith("notice.") ||
    base.startsWith("license-") ||
    base.startsWith("licence-") ||
    base.startsWith("copying-") ||
    base.startsWith("notice-")
  );
}

function findLicenseFile(packageDir) {
  const preferred = [
    "LICENSE",
    "LICENSE.txt",
    "LICENSE.md",
    "LICENCE",
    "LICENCE.txt",
    "COPYING",
    "COPYING.txt",
    "NOTICE",
    "NOTICE.txt",
    "LICENSE-MIT",
    "LICENSE-APACHE",
  ];

  for (const name of preferred) {
    const abs = path.join(packageDir, name);
    try {
      const stat = fs.statSync(abs);
      if (stat.isFile()) return name;
    } catch {
      // ignore
    }
  }

  let entries;
  try {
    entries = fs.readdirSync(packageDir, { withFileTypes: true });
  } catch {
    return null;
  }

  // Stable ordering across platforms.
  entries.sort((a, b) => a.name.localeCompare(b.name));

  for (const entry of entries) {
    if (!entry.isFile()) continue;
    if (!isTextFileCandidate(entry.name)) continue;
    return entry.name;
  }

  return null;
}

function safeReadTextFile(filePath, maxBytes) {
  try {
    const stat = fs.statSync(filePath);
    if (!stat.isFile()) return null;
    if (stat.size > maxBytes) return `<<omitted: file is ${stat.size} bytes>>`;
    return fs.readFileSync(filePath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    return null;
  }
}

if (!fs.existsSync(lockPath)) {
  console.error(`Missing ${lockPath}. Run npm install first.`);
  process.exit(1);
}

const lock = JSON.parse(fs.readFileSync(lockPath, "utf8"));
const packages = lock.packages || {};

const itemsById = new Map();

for (const [pkgPath, meta] of Object.entries(packages)) {
  if (!pkgPath.startsWith("node_modules/")) continue;

  const absDir = path.join(repoRoot, pkgPath);
  const pkgJsonPath = path.join(absDir, "package.json");
  if (!fs.existsSync(pkgJsonPath)) continue;

  let pkgJson;
  try {
    pkgJson = JSON.parse(fs.readFileSync(pkgJsonPath, "utf8"));
  } catch {
    continue;
  }

  const name = pkgJson.name || meta?.name;
  const version = pkgJson.version || meta?.version;
  if (!name || !version) continue;

  const license = normalizeLicense(pkgJson.license || pkgJson.licenses || meta?.license);
  const repository = repoToUrl(pkgJson.repository);
  const homepage = typeof pkgJson.homepage === "string" ? pkgJson.homepage : null;

  const licenseFile = findLicenseFile(absDir);
  const licenseText = licenseFile
    ? safeReadTextFile(path.join(absDir, licenseFile), 1024 * 1024)
    : null;

  const id = `${name}@${version}`;
  const candidate = {
    pkgPath,
    name,
    version,
    license,
    repository,
    homepage,
    licenseFile,
    licenseText,
  };

  const existing = itemsById.get(id);
  if (!existing) {
    itemsById.set(id, candidate);
    continue;
  }

  // Prefer an entry that has license text and/or a license file reference.
  if (!existing.licenseText && candidate.licenseText) {
    itemsById.set(id, candidate);
  } else if (!existing.licenseFile && candidate.licenseFile) {
    itemsById.set(id, candidate);
  }
}

const items = [...itemsById.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
);

const lines = [];
lines.push("THIRD-PARTY NOTICES");
lines.push("===================");
lines.push("");
lines.push("This file lists third-party dependencies and their licenses.");
lines.push("Generated by: scripts/generate-third-party-notices.mjs");
lines.push("");
lines.push("Project license: see LICENSE");
lines.push("");
lines.push("SUMMARY");
lines.push("-------");
for (const item of items) {
  lines.push(`${item.name}@${item.version}  (${item.license})`);
}
lines.push("");
lines.push("LICENSE TEXTS");
lines.push("-------------");

for (const item of items) {
  lines.push("");
  lines.push("--------------------------------------------------------------------------------");
  lines.push(`${item.name}@${item.version}`);
  lines.push(`License: ${item.license}`);
  if (item.repository) lines.push(`Repository: ${item.repository}`);
  if (item.homepage) lines.push(`Homepage: ${item.homepage}`);
  if (item.licenseFile) lines.push(`License file: ${path.posix.join(item.pkgPath, item.licenseFile)}`);
  lines.push("");
  if (item.licenseText) {
    lines.push(item.licenseText.trimEnd());
  } else {
    lines.push("<<license text not found in installed package>>");
  }
}

lines.push("");

fs.writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${items.length} packages).`);
